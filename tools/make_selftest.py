"""Generate include/selftest.h: every held-out test window (sessions 3 and 5),
its raw samples, the features computed in Python, and Python's predicted class.
The board replays these windows through its own C feature code and tree at boot
and compares (see selftest_run() in src/main.c).

Run from the project root:  python tools/make_selftest.py
"""
import glob, os
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier

WIN = 100
TEST_SESSIONS = {3, 5}

def features(w):
    acc = w[:, 0:3] / 8192.0
    gyr = w[:, 3:6] / 65.5
    mag = np.linalg.norm(acc, axis=1)
    f = []
    for ch in np.hstack([acc, gyr]).T:
        f += [ch.mean(), ch.std(), ch.min(), ch.max()]
    f += [mag.mean(), mag.std(), w[:, 6].max(), w[:, 7].mean()]
    return f

X_tr, y_tr = [], []
test = []                                    # (label, raw window, features)
for path in sorted(glob.glob("data/*_0?.csv")):
    label, sess = os.path.basename(path)[:-4].split("_")
    d = pd.read_csv(path)[["ax", "ay", "az", "gx", "gy", "gz", "ps", "als"]].to_numpy(dtype=float)
    for s in range(0, len(d) - WIN + 1, WIN):
        w = d[s:s + WIN]
        f = features(w)
        if int(sess) in TEST_SESSIONS:
            test.append((label, w, f))
        else:
            X_tr.append(f); y_tr.append(label)

model = DecisionTreeClassifier(max_depth=5, random_state=0).fit(np.array(X_tr), y_tr)
pred = model.predict(np.array([t[2] for t in test]))
n = len(test)
ok = sum(p == t[0] for p, t in zip(pred, test))
print(f"{n} test windows; Python tree correct on {ok}/{n}")

with open("include/selftest.h", "w") as fh:
    fh.write("/* generated by tools/make_selftest.py - do not edit */\n#pragma once\n")
    fh.write(f"#define SELFTEST_N {n}\n")
    fh.write("static const sample_t selftest_win[SELFTEST_N][WIN_N] = {\n")
    for _, w, _ in test:
        fh.write("{")
        for r in w.astype(int):
            fh.write("{{%d,%d,%d,%d,%d,%d},%d,%d}," % tuple(r))
        fh.write("},\n")
    fh.write("};\n")
    fh.write("static const float selftest_feat[SELFTEST_N][N_FEATURES] = {\n")
    for _, _, f in test:
        fh.write("{" + ",".join("%.9ef" % v for v in f) + "},\n")
    fh.write("};\n")
    fh.write("static const char *const selftest_cls[SELFTEST_N] = {\n")
    fh.write(",".join('"%s"' % p.upper() for p in pred) + "\n};\n")
print("wrote include/selftest.h")
